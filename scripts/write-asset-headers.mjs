// Runs before every `next build` (npm's prebuild hook; OpenNext's build runs
// `npm run build` too).
//
// Files in public/ (images, icons, the web manifest) are served by
// Cloudflare's static assets straight from the edge, without the Worker, so
// the X-Robots-Tag header from next.config.ts never reaches them. On every
// build that is not levuche.com (the dev site and preview links), this
// writes public/_headers, which Cloudflare applies to those files. On a
// levuche.com build it removes the file, so production is unchanged.
//
// public/_headers is generated: it is in .gitignore, never commit it.

import { rm, writeFile } from 'node:fs/promises';

const PRODUCTION_URL = 'https://levuche.com';
const siteUrl = (
  process.env.NEXT_PUBLIC_SITE_URL?.trim() || PRODUCTION_URL
).replace(/\/+$/, '');
const file = new URL('../public/_headers', import.meta.url);

if (siteUrl === PRODUCTION_URL) {
  await rm(file, { force: true });
  console.log('public/_headers: none (levuche.com build)');
} else {
  await writeFile(
    file,
    [
      '# Generated by scripts/write-asset-headers.mjs for ' + siteUrl,
      '# Keeps the files in public/ out of search results. Do not commit.',
      '/*',
      '  X-Robots-Tag: noindex, nofollow',
      '',
    ].join('\n')
  );
  console.log(`public/_headers: noindex (${siteUrl} build)`);
}
